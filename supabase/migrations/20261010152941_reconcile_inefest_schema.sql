create or replace function public.enforce_registration_capacity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
	competition_row public.kompetisi%rowtype;
	current_count bigint;
begin
	select * into competition_row
	from public.kompetisi
	where id_kompetisi = new.id_kompetisi
	for update;

	if competition_row.id_kompetisi is null
		 or competition_row.status <> 'aktif'
		 or competition_row.deadline_pendaftaran <= now() then
		raise exception 'competition_unavailable' using errcode = 'P0001';
	end if;

	select count(*) into current_count
	from public.pendaftaran
	where id_kompetisi = new.id_kompetisi and status_verifikasi <> 'Rejected';

	if competition_row.kuota_maksimal is not null and current_count >= competition_row.kuota_maksimal then
		raise exception 'competition_full' using errcode = 'P0001';
	end if;
	return new;
end;
$$;

create or replace function public.write_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
	event_action text;
	event_type text := tg_argv[0];
	event_id text;
	event_metadata jsonb := '{}'::jsonb;
begin
	if tg_op = 'INSERT' then
		event_action := case when event_type = 'registration' then 'REGISTER' else 'CREATE' end;
	elsif tg_op = 'DELETE' then
		event_action := 'DELETE';
	elsif event_type = 'registration' then
		if old.status_verifikasi is distinct from new.status_verifikasi then
			event_action := 'VERIFY';
			event_metadata := jsonb_build_object('from', old.status_verifikasi, 'to', new.status_verifikasi);
		else
			event_action := 'UPDATE';
		end if;
	else
		event_action := 'UPDATE';
	end if;

	if tg_op = 'DELETE' then
		if event_type = 'competition' then
			event_id := old.id_kompetisi::text;
		elsif event_type = 'participant' then
			event_id := old.id::text;
		elsif event_type = 'registration' then
			event_id := old.id_pendaftaran::text;
		elsif event_type = 'hero' then
			event_id := old.id_hero::text;
		elsif event_type = 'partner' then
			event_id := old.id_partner::text;
		end if;
	else
		if event_type = 'competition' then
			event_id := new.id_kompetisi::text;
		elsif event_type = 'participant' then
			event_id := new.id::text;
		elsif event_type = 'registration' then
			event_id := new.id_pendaftaran::text;
		elsif event_type = 'hero' then
			event_id := new.id_hero::text;
		elsif event_type = 'partner' then
			event_id := new.id_partner::text;
		end if;
	end if;

	insert into public.audit_logs (actor_id, action, entity_type, entity_id, metadata)
	values (auth.uid(), event_action, event_type, event_id, event_metadata);
	return null;
end;
$$;

