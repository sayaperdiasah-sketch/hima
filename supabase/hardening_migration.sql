create or replace function public.enforce_registration_capacity()
returns trigger language plpgsql security definer set search_path = public as $$
declare competition_row public.kompetisi%rowtype; current_count bigint;
begin
  select * into competition_row from public.kompetisi where id_kompetisi = new.id_kompetisi for update;
  if competition_row.id_kompetisi is null or competition_row.status <> 'aktif' or competition_row.deadline_pendaftaran <= now() then
    raise exception 'competition_unavailable' using errcode = 'P0001';
  end if;
  select count(*) into current_count from public.pendaftaran where id_kompetisi = new.id_kompetisi and status_verifikasi <> 'Rejected';
  if competition_row.kuota_maksimal is not null and current_count >= competition_row.kuota_maksimal then
    raise exception 'competition_full' using errcode = 'P0001';
  end if;
  return new;
end $$;

drop trigger if exists pendaftaran_enforce_capacity on public.pendaftaran;
create trigger pendaftaran_enforce_capacity before insert on public.pendaftaran for each row execute procedure public.enforce_registration_capacity();

create or replace function public.write_audit_log()
returns trigger language plpgsql security definer set search_path = public as $$
declare event_action text; event_type text := tg_argv[0]; event_id text; event_metadata jsonb := '{}'::jsonb;
begin
  if tg_op = 'INSERT' then event_action := case when event_type = 'registration' then 'REGISTER' else 'CREATE' end;
  elsif tg_op = 'DELETE' then event_action := 'DELETE';
  elsif event_type = 'registration' and old.status_verifikasi is distinct from new.status_verifikasi then
    event_action := 'VERIFY'; event_metadata := jsonb_build_object('from', old.status_verifikasi, 'to', new.status_verifikasi);
  else event_action := 'UPDATE'; end if;
  event_id := case event_type when 'competition' then coalesce(new.id_kompetisi, old.id_kompetisi)::text when 'registration' then coalesce(new.id_pendaftaran, old.id_pendaftaran)::text when 'hero' then coalesce(new.id_hero, old.id_hero)::text when 'partner' then coalesce(new.id_partner, old.id_partner)::text end;
  insert into public.audit_logs (actor_id, action, entity_type, entity_id, metadata) values (auth.uid(), event_action, event_type, event_id, event_metadata);
  return null;
end $$;

