-- KompetisiKita secure Supabase schema
-- Run this in the Supabase SQL Editor on a new project.

create extension if not exists pgcrypto;

create table public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  nama_lengkap text not null default '',
  instansi text,
  no_whatsapp text,
  created_at timestamptz not null default now()
);

create table public.admin_users (
  user_id uuid references auth.users(id) on delete cascade primary key,
  nama_lengkap text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.kompetisi (
  id_kompetisi bigint generated by default as identity primary key,
  nama_kompetisi text not null,
  kategori text not null,
  deskripsi text not null,
  target_peserta text not null default 'Umum',
  total_hadiah text,
  biaya_pendaftaran integer not null default 0 check (biaya_pendaftaran >= 0),
  kuota_maksimal integer check (kuota_maksimal > 0),
  deadline_pendaftaran timestamptz not null,
  poster_path text,
  status text not null default 'aktif' check (status in ('draft', 'aktif', 'ditutup')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.pendaftaran (
  id_pendaftaran bigint generated by default as identity primary key,
  id_user uuid not null references public.profiles(id) on delete cascade,
  id_kompetisi bigint not null references public.kompetisi(id_kompetisi) on delete cascade,
  nama_tim text not null,
  nama_ketua text not null,
  instansi text not null,
  no_whatsapp text not null,
  file_karya_path text,
  bukti_bayar_path text,
  status_verifikasi text not null default 'Pending' check (status_verifikasi in ('Pending', 'Approved', 'Rejected')),
  catatan_admin text,
  verified_by uuid references public.admin_users(user_id),
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (id_user, id_kompetisi)
);

create index pendaftaran_user_idx on public.pendaftaran (id_user);
create index pendaftaran_kompetisi_idx on public.pendaftaran (id_kompetisi);
create index pendaftaran_status_idx on public.pendaftaran (status_verifikasi);
create index kompetisi_status_deadline_idx on public.kompetisi (status, deadline_pendaftaran);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid() and is_active = true
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.get_active_competitions()
returns table (
  id_kompetisi bigint,
  nama_kompetisi text,
  kategori text,
  deskripsi text,
  target_peserta text,
  total_hadiah text,
  biaya_pendaftaran integer,
  kuota_maksimal integer,
  deadline_pendaftaran timestamptz,
  poster_path text,
  status text,
  pendaftar_count bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select
    k.id_kompetisi,
    k.nama_kompetisi,
    k.kategori,
    k.deskripsi,
    k.target_peserta,
    k.total_hadiah,
    k.biaya_pendaftaran,
    k.kuota_maksimal,
    k.deadline_pendaftaran,
    k.poster_path,
    k.status,
    (select count(*) from public.pendaftaran p where p.id_kompetisi = k.id_kompetisi) as pendaftar_count
  from public.kompetisi k
  where k.status = 'aktif' and k.deadline_pendaftaran > now()
  order by k.deadline_pendaftaran asc;
$$;

revoke all on function public.get_active_competitions() from public;
grant execute on function public.get_active_competitions() to anon, authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nama_lengkap)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'nama_lengkap', ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;

create trigger kompetisi_set_updated_at
  before update on public.kompetisi
  for each row execute procedure public.set_updated_at();

alter table public.profiles enable row level security;
alter table public.admin_users enable row level security;
alter table public.kompetisi enable row level security;
alter table public.pendaftaran enable row level security;

create policy "profile read own or admin" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

create policy "profile update own" on public.profiles
  for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

create policy "admin can verify own role" on public.admin_users
  for select to authenticated
  using (user_id = auth.uid());

create policy "public reads active competitions" on public.kompetisi
  for select to anon, authenticated
  using (status = 'aktif');

create policy "admin reads all competitions" on public.kompetisi
  for select to authenticated
  using (public.is_admin());

create policy "admin inserts competitions" on public.kompetisi
  for insert to authenticated with check (public.is_admin());
create policy "admin updates competitions" on public.kompetisi
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin deletes competitions" on public.kompetisi
  for delete to authenticated using (public.is_admin());

create policy "participant reads own registrations" on public.pendaftaran
  for select to authenticated
  using (id_user = auth.uid() or public.is_admin());

create policy "participant inserts own registration" on public.pendaftaran
  for insert to authenticated
  with check (
    id_user = auth.uid()
    and status_verifikasi = 'Pending'
    and exists (
      select 1 from public.kompetisi k
      where k.id_kompetisi = id_kompetisi
        and k.status = 'aktif'
        and k.deadline_pendaftaran > now()
    )
  );

create policy "admin updates registrations" on public.pendaftaran
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create policy "admin deletes registrations" on public.pendaftaran
  for delete to authenticated using (public.is_admin());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('posters', 'posters', true, 5242880, array['image/jpeg','image/png','image/webp']),
  ('karya', 'karya', false, 10485760, array['application/pdf','image/jpeg','image/png','application/zip']),
  ('bukti-bayar', 'bukti-bayar', false, 5242880, array['application/pdf','image/jpeg','image/png'])
on conflict (id) do nothing;

create policy "public reads posters" on storage.objects
  for select to public using (bucket_id = 'posters');
create policy "admin manages posters" on storage.objects
  for all to authenticated
  using (bucket_id = 'posters' and public.is_admin())
  with check (bucket_id = 'posters' and public.is_admin());

create policy "participant uploads own work" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'karya' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "participant reads own work" on storage.objects
  for select to authenticated
  using (bucket_id = 'karya' and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin()));

create policy "participant uploads own payment" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'bukti-bayar' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "participant reads own payment" on storage.objects
  for select to authenticated
  using (bucket_id = 'bukti-bayar' and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin()));

