create policy "profile read own or admin" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

create policy "profile update own" on public.profiles
  for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

create policy "admin can verify own role" on public.admin_users
  for select to authenticated
  using (user_id = auth.uid());

create policy "public reads active competitions" on public.kompetisi
  for select to anon, authenticated
  using (status = 'aktif');

create policy "admin reads all competitions" on public.kompetisi
  for select to authenticated
  using (public.is_admin());

create policy "admin inserts competitions" on public.kompetisi
  for insert to authenticated with check (public.is_admin());
create policy "admin updates competitions" on public.kompetisi
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin deletes competitions" on public.kompetisi
  for delete to authenticated using (public.is_admin());

create policy "participant reads own registrations" on public.pendaftaran
  for select to authenticated
  using (id_user = auth.uid() or public.is_admin());

create policy "participant inserts own registration" on public.pendaftaran
  for insert to authenticated
  with check (
    id_user = auth.uid()
    and status_verifikasi = 'Pending'
    and exists (
      select 1 from public.kompetisi k
      where k.id_kompetisi = id_kompetisi
        and k.status = 'aktif'
        and k.deadline_pendaftaran > now()
    )
  );

create policy "admin updates registrations" on public.pendaftaran
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create policy "admin deletes registrations" on public.pendaftaran
  for delete to authenticated using (public.is_admin());

