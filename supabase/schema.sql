create extension if not exists pgcrypto;

create table public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  nama_lengkap text not null default '',
  instansi text,
  no_whatsapp text,
  created_at timestamptz not null default now()
);

create table public.admin_users (
  user_id uuid references auth.users(id) on delete cascade primary key,
  nama_lengkap text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.kompetisi (
  id_kompetisi bigint generated by default as identity primary key,
  nama_kompetisi text not null,
  kategori text not null,
  deskripsi text not null,
  target_peserta text not null default 'Umum',
  total_hadiah text,
  biaya_pendaftaran integer not null default 0 check (biaya_pendaftaran >= 0),
  kuota_maksimal integer check (kuota_maksimal > 0),
  deadline_pendaftaran timestamptz not null,
  poster_path text,
  status text not null default 'aktif' check (status in ('draft', 'aktif', 'ditutup')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.pendaftaran (
  id_pendaftaran bigint generated by default as identity primary key,
  id_user uuid not null references public.profiles(id) on delete cascade,
  id_kompetisi bigint not null references public.kompetisi(id_kompetisi) on delete cascade,
  nama_tim text not null,
  nama_ketua text not null,
  instansi text not null,
  no_whatsapp text not null,
  file_karya_path text,
  bukti_bayar_path text,
  status_verifikasi text not null default 'Pending' check (status_verifikasi in ('Pending', 'Approved', 'Rejected')),
  catatan_admin text,
  verified_by uuid references public.admin_users(user_id),
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (id_user, id_kompetisi),
  check (char_length(btrim(nama_tim)) between 2 and 80),
  check (char_length(btrim(nama_ketua)) between 2 and 100),
  check (char_length(btrim(instansi)) between 2 and 140),
  check (no_whatsapp ~ '^08[0-9]{8,12}$'),
  check (catatan_admin is null or char_length(catatan_admin) <= 1000)
);

create table public.hero_slides (
  id_hero bigint generated by default as identity primary key,
  slot_number smallint not null unique check (slot_number between 1 and 3),
  title text not null check (char_length(btrim(title)) between 3 and 120),
  subtitle text not null check (char_length(btrim(subtitle)) between 5 and 300),
  image_path text,
  cta_label text not null default 'Lihat kompetisi' check (char_length(cta_label) between 2 and 40),
  cta_url text not null default '#/kompetisi' check (char_length(cta_url) between 1 and 240),
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.audit_logs (
  id_log bigint generated always as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null check (action in ('CREATE', 'UPDATE', 'DELETE', 'REGISTER', 'VERIFY', 'LOGIN')),
  entity_type text not null check (entity_type in ('competition', 'registration', 'hero', 'admin_session')),
  entity_id text,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);

create index pendaftaran_user_idx on public.pendaftaran (id_user);
create index pendaftaran_kompetisi_idx on public.pendaftaran (id_kompetisi);
create index pendaftaran_status_idx on public.pendaftaran (status_verifikasi);
create index kompetisi_status_deadline_idx on public.kompetisi (status, deadline_pendaftaran);
create index audit_logs_created_idx on public.audit_logs (created_at desc);
create index audit_logs_entity_idx on public.audit_logs (entity_type, entity_id);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid() and is_active = true
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.get_active_competitions()
returns table (
  id_kompetisi bigint,
  nama_kompetisi text,
  kategori text,
  deskripsi text,
  target_peserta text,
  total_hadiah text,
  biaya_pendaftaran integer,
  kuota_maksimal integer,
  deadline_pendaftaran timestamptz,
  poster_path text,
  status text,
  pendaftar_count bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select
    k.id_kompetisi,
    k.nama_kompetisi,
    k.kategori,
    k.deskripsi,
    k.target_peserta,
    k.total_hadiah,
    k.biaya_pendaftaran,
    k.kuota_maksimal,
    k.deadline_pendaftaran,
    k.poster_path,
    k.status,
    (select count(*) from public.pendaftaran p where p.id_kompetisi = k.id_kompetisi) as pendaftar_count
  from public.kompetisi k
  where k.status = 'aktif' and k.deadline_pendaftaran > now()
  order by k.deadline_pendaftaran asc;
$$;

revoke all on function public.get_active_competitions() from public;
grant execute on function public.get_active_competitions() to anon, authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nama_lengkap)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'nama_lengkap', ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

