create or replace function public.enforce_registration_capacity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  competition_row public.kompetisi%rowtype;
  current_count bigint;
begin
  select * into competition_row
  from public.kompetisi
  where id_kompetisi = new.id_kompetisi
  for update;

  if competition_row.id_kompetisi is null
     or competition_row.status <> 'aktif'
     or competition_row.deadline_pendaftaran <= now() then
    raise exception 'competition_unavailable' using errcode = 'P0001';
  end if;

  select count(*) into current_count
  from public.pendaftaran
  where id_kompetisi = new.id_kompetisi
    and status_verifikasi <> 'Rejected';

  if competition_row.kuota_maksimal is not null and current_count >= competition_row.kuota_maksimal then
    raise exception 'competition_full' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

create trigger pendaftaran_enforce_capacity
  before insert on public.pendaftaran
  for each row execute procedure public.enforce_registration_capacity();

create or replace function public.write_audit_log()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  event_action text;
  event_type text := tg_argv[0];
  event_id text;
  event_metadata jsonb := '{}'::jsonb;
begin
  if tg_op = 'INSERT' then
    event_action := case when event_type = 'registration' then 'REGISTER' else 'CREATE' end;
  elsif tg_op = 'DELETE' then
    event_action := 'DELETE';
  elsif event_type = 'registration' and old.status_verifikasi is distinct from new.status_verifikasi then
    event_action := 'VERIFY';
    event_metadata := jsonb_build_object('from', old.status_verifikasi, 'to', new.status_verifikasi);
  else
    event_action := 'UPDATE';
  end if;

  event_id := case event_type
    when 'competition' then coalesce(new.id_kompetisi, old.id_kompetisi)::text
    when 'registration' then coalesce(new.id_pendaftaran, old.id_pendaftaran)::text
    when 'hero' then coalesce(new.id_hero, old.id_hero)::text
  end;

  insert into public.audit_logs (actor_id, action, entity_type, entity_id, metadata)
  values (auth.uid(), event_action, event_type, event_id, event_metadata);
  return null;
end;
$$;

create trigger audit_competition_changes after insert or update or delete on public.kompetisi
  for each row execute procedure public.write_audit_log('competition');
create trigger audit_registration_changes after insert or update or delete on public.pendaftaran
  for each row execute procedure public.write_audit_log('registration');
create trigger audit_hero_changes after insert or update or delete on public.hero_slides
  for each row execute procedure public.write_audit_log('hero');

create or replace function public.record_admin_login()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;
  insert into public.audit_logs (actor_id, action, entity_type, entity_id)
  values (auth.uid(), 'LOGIN', 'admin_session', auth.uid()::text);
end;
$$;

revoke all on function public.record_admin_login() from public;
grant execute on function public.record_admin_login() to authenticated;

