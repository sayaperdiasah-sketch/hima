create table public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  nama_lengkap text not null default '',
  instansi text,
  no_whatsapp text,
  created_at timestamptz not null default now()
);

create table public.admin_users (
  user_id uuid references auth.users(id) on delete cascade primary key,
  nama_lengkap text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.kompetisi (
  id_kompetisi bigint generated by default as identity primary key,
  nama_kompetisi text not null,
  kategori text not null,
  deskripsi text not null,
  target_peserta text not null default 'Umum',
  total_hadiah text,
  biaya_pendaftaran integer not null default 0 check (biaya_pendaftaran >= 0),
  kuota_maksimal integer check (kuota_maksimal > 0),
  jenis_peserta text not null default 'kelompok' check (jenis_peserta in ('individu', 'kelompok')),
  minimal_anggota smallint not null default 2,
  maksimal_anggota smallint not null default 5,
  whatsapp_group_url text check (
    whatsapp_group_url is null
    or whatsapp_group_url ~ '^https://chat\.whatsapp\.com/[A-Za-z0-9_-]+/?([?][^[:space:]]*)?$'
  ),
  deadline_pendaftaran timestamptz not null,
  poster_path text,
  status text not null default 'aktif' check (status in ('draft', 'aktif', 'ditutup')),
  check (
    (jenis_peserta = 'individu' and minimal_anggota = 1 and maksimal_anggota = 1)
    or (jenis_peserta = 'kelompok' and minimal_anggota between 2 and maksimal_anggota and maksimal_anggota <= 20)
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.pendaftaran (
  id_pendaftaran bigint generated by default as identity primary key,
  id_user uuid references public.profiles(id) on delete set null,
  id_kompetisi bigint not null references public.kompetisi(id_kompetisi) on delete cascade,
  nama_tim text not null,
  nama_ketua text not null,
  email_ketua text not null,
  instansi text not null,
  no_whatsapp text not null,
  anggota jsonb not null default '[]'::jsonb check (jsonb_typeof(anggota) = 'array'),
  file_karya_path text,
  bukti_bayar_path text,
  status_verifikasi text not null default 'Pending' check (status_verifikasi in ('Pending', 'Approved', 'Rejected')),
  catatan_admin text,
  verified_by uuid references public.admin_users(user_id),
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  check (char_length(btrim(nama_tim)) between 2 and 80),
  check (char_length(btrim(nama_ketua)) between 2 and 100),
  check (email_ketua ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  check (char_length(btrim(instansi)) between 2 and 140),
  check (no_whatsapp ~ '^08[0-9]{8,12}$'),
  check (catatan_admin is null or char_length(catatan_admin) <= 1000)
);

create table public.hero_slides (
  id_hero bigint generated by default as identity primary key,
  slot_number smallint not null unique check (slot_number between 1 and 3),
  title text not null check (char_length(btrim(title)) between 3 and 120),
  subtitle text not null check (char_length(btrim(subtitle)) between 5 and 300),
  image_path text,
  cta_label text not null default 'Lihat kompetisi' check (char_length(cta_label) between 2 and 40),
  cta_url text not null default '#/kompetisi' check (char_length(cta_url) between 1 and 240),
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.event_partners (
  id_partner bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 2 and 100),
  tier text not null check (tier in ('utama', 'pendukung', 'komunitas', 'media')),
  logo_path text not null,
  website_url text check (website_url is null or website_url ~ '^https?://'),
  sort_order smallint not null default 10 check (sort_order between 0 and 999),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.audit_logs (
